# Make src/shorts/<id>/timing.ts from words.json and copy the voice + make music.
# Usage: python3 mktiming.py SHORT_DIR ID SEED key=word[:n] ...   (n = which occurrence, 1-based; matching ignores case/punctuation)
import sys, json, re, os, shutil, subprocess
d, sid, seed = sys.argv[1], sys.argv[2], sys.argv[3]
W = json.load(open(f'{d}/words.json')); words = W['words']; VO = 0.1
norm = lambda s: re.sub(r"(?<![0-9])\.|\.(?![0-9])", '', re.sub(r"[^a-z0-9%.']", '', s.lower()))
T = {}
for kv in sys.argv[4:]:
    k, w = kv.split('='); n = 1
    if ':' in w: w, n = w.split(':'); n = int(n)
    hits = [x for x in words if norm(x['w']) == norm(w)]
    if len(hits) < n: sys.exit(f'word not found: {w}#{n} in ' + ' '.join(x['w'] for x in words))
    T[k] = round(hits[n - 1]['s'] + VO, 3)
vend = round(words[-1]['e'] + VO, 3); T['vend'] = vend; T['card'] = round(vend + 0.35, 3); T['end'] = round(vend + 0.35 + 2.8, 3)
root = os.path.dirname(os.path.abspath(__file__)) + '/../remotion'
os.makedirs(f'{root}/src/shorts/{sid}', exist_ok=True); os.makedirs(f'{root}/public/{sid}', exist_ok=True)
open(f'{root}/src/shorts/{sid}/timing.ts', 'w').write('// generated by tools/mktiming.py from words.json (voice at 0.1 s)\nexport const VO_AT = 0.1;\nexport const T = ' + json.dumps(T, indent=1) + ';\n')
shutil.copy(f'{d}/vo.wav', f'{root}/public/{sid}/vo.wav')
subprocess.run(['python3', os.path.dirname(os.path.abspath(__file__)) + '/mkmusic.py', f'{root}/public/{sid}/music.wav', str(T['end'] + 1), str(96 + int(seed) % 5 * 4), seed], check=True)
print(sid, T)
